"""
Notification and PR Comment Formatter.
Generates GitHub-flavored markdown summaries, PR review comments, and webhook payloads.
"""

import os
from typing import Optional
import httpx
from src.models import AnalysisReport, ImpactFinding


def generate_pr_comment_markdown(report: AnalysisReport) -> str:
    """Creates a formatted GitHub PR review comment body."""
    # Architecture Overview Section (from GitHub Repo Analyzer integration)
    arch_section = ""
    if report.repo_architectures:
        arch_section = "### 🏛️ Repository Architecture Overviews\n\n"
        for repo_name, arch in report.repo_architectures.items():
            frameworks_str = ", ".join(arch.frameworks) if arch.frameworks else "Java SE"
            arch_section += (
                f"- **`{repo_name}`** ({arch.role_in_contract}):\n"
                f"  - **Language & Stack**: {arch.primary_language} ({arch.build_tool})\n"
                f"  - **Frameworks & Libs**: {frameworks_str}\n"
                f"  - **Description**: {arch.description}\n\n"
            )

    if not report.findings:
        return (
            "### :white_check_mark: Cross-Repository Dependency Guardian: No Incompatibilities Found\n\n"
            + arch_section
            + f"Scanned changed Java files against **{len(report.target_repos_checked)}** registered dependent repositories. "
            "No contract breakages or missing updates were identified."
        )

    header = (
        "## :rotating_light: Cross-Repository Dependency Alert!\n\n"
        f"The changes in this PR affect contracts in **{len(report.findings)}** dependent file(s) across target repositories. "
        "Failing to update these repositories simultaneously will likely cause production failures.\n\n"
    )

    table_header = (
        "| Severity | Dependent Repo | Dependent File & Line | Source Trigger & Line | Dependency Type |\n"
        "| :---: | :--- | :--- | :--- | :--- |\n"
    )

    rows = []
    for f in report.findings:
        badge = (
            ":red_circle: **CRITICAL**"
            if f.severity == "CRITICAL"
            else ":orange_circle: **HIGH**"
            if f.severity == "HIGH"
            else ":yellow_circle: **MEDIUM**"
        )
        target_loc = f"`{f.target_file}`" + (f" (L{f.target_line})" if f.target_line else "")
        source_loc = f"`{f.source_file}`" + (f" (L{f.source_line})" if f.source_line else "")

        rows.append(
            f"| {badge} | `{f.target_repo}` | {target_loc} | {source_loc} | `{f.dependency_type}` |"
        )

    table = table_header + "\n".join(rows) + "\n\n"

    details = "### Detailed Impact & Suggested Fixes\n\n"
    for idx, f in enumerate(report.findings, start=1):
        target_loc = f"`{f.target_file}`" + (f" (Line {f.target_line})" if f.target_line else "")
        source_loc = f"`{f.source_file}`" + (f" (Line {f.source_line})" if f.source_line else "")

        details += f"#### {idx}. [{f.target_repo}] {target_loc}\n"
        details += f"- **Triggered by**: {source_loc}\n"
        details += f"- **Summary**: {f.breaking_change_summary}\n\n"
        details += f"**Why it breaks:**\n{f.detailed_reason}\n\n"
        details += f"**Action Required:**\n{f.suggested_fix}\n\n"
        if f.suggested_patch_code:
            details += f"```java\n{f.suggested_patch_code}\n```\n\n"

    footer = (
        "---\n"
        "*Generated by AI Cross-Repo Dependency Guardian with GitHub Repo Analyzer. Configured via `repo_dependency_mapping.xlsx`.*"
    )

    return header + arch_section + table + details + footer


def write_step_summary(report: AnalysisReport, output_path: Optional[str] = None):
    """Writes the markdown summary to $GITHUB_STEP_SUMMARY for CI display."""
    summary_path = output_path or os.getenv("GITHUB_STEP_SUMMARY")
    if not summary_path:
        return

    md = generate_pr_comment_markdown(report)
    try:
        with open(summary_path, "a", encoding="utf-8") as f:
            f.write("\n" + md + "\n")
    except Exception as e:
        print(f"Warning: Failed to write to GITHUB_STEP_SUMMARY: {e}")


def send_slack_notification(webhook_url: str, report: AnalysisReport) -> bool:
    """Send alert to Slack channel if webhook URL is configured."""
    if not webhook_url or not report.findings:
        return False

    text = f":warning: *Cross-Repo Dependency Alert* in `{report.source_repo}`!\n"
    text += f"{len(report.findings)} dependent repository files require corresponding updates.\n"
    for f in report.findings[:3]:
        text += f"- *[{f.severity}]* `{f.target_repo}` -> `{f.target_file}`\n"

    payload = {"text": text}
    try:
        res = httpx.post(webhook_url, json=payload, timeout=10.0)
        return res.status_code == 200
    except Exception:
        return False
